create table if not exists public.integrations (
  id bigint generated by default as identity primary key,
  site_id text not null references public.sites(site_id) on delete cascade,
  provider text not null,
  destination_id text,
  credentials text not null,
  webhook_secret text,
  enabled boolean not null default true,
  config jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists integrations_site_id_idx on public.integrations(site_id);

create table if not exists public.pending_replies (
  id bigint generated by default as identity primary key,
  conversation_id text not null references public.conversations(conversation_id) on delete cascade,
  reply text not null,
  created_at timestamptz not null default now()
);
create index if not exists pending_replies_conversation_idx on public.pending_replies(conversation_id);

create table if not exists public.site_stats (
  site_id text primary key references public.sites(site_id) on delete cascade,
  messages_received bigint not null default 0,
  replies_sent bigint not null default 0,
  last_message_at timestamptz
);

